#!/usr/bin/env node
/**
 * Turn content/primers/<slug>/primer.ts (plus its ./code snippets) into an
 * idempotent upsert migration for public.primers.
 *
 *   node --experimental-strip-types scripts/primers-to-sql.mjs 20261115000002
 *
 * Applied migrations are never edited, so every content change gets a new
 * version: the file upserts ALL primers on slug, and running it again is a
 * no-op. Only authorless rows (the hand-written set) are touched; a squad
 * member's own primer with the same slug is left alone.
 *
 * Run scripts/check-primer-code.mjs first: this script copies the snippets'
 * visible part ("---- code ----" to "---- checks ----") but doesn't run them.
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CONTENT = path.join(ROOT, "content/primers");
const version = process.argv[2];
if (!/^\d{14}$/.test(version ?? "")) {
  console.error("Usage: primers-to-sql.mjs <14-digit migration version>");
  process.exit(2);
}

const LANGS = { python: "py", cpp: "cpp", java: "java" };

/** The part of a snippet a reader sees. */
function visible(file) {
  const src = readFileSync(file, "utf8");
  const start = src.search(/^\s*(\/\/|#) ---- code ----\s*$/m);
  const from = start < 0 ? 0 : src.indexOf("\n", start) + 1;
  const end = src.search(/^\s*(\/\/|#) ---- checks ----\s*$/m);
  return src.slice(from, end < 0 ? undefined : end).replace(/\s+$/, "") + "\n";
}

function code(slug, ref) {
  const out = {};
  for (const [lang, ext] of Object.entries(LANGS)) {
    const file = path.join(CONTENT, slug, "code", `${ref}.${ext}`);
    if (!existsSync(file)) throw new Error(`${slug}: missing code/${ref}.${ext}`);
    out[lang] = visible(file);
  }
  return out;
}

const lit = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(lit).join(", ")}]::text[]`;
const json = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`;

const slugs = readdirSync(CONTENT, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(CONTENT, d.name, "primer.ts")))
  .map((d) => d.name)
  .sort();

const rows = [];
for (const slug of slugs) {
  const { primer: p } = await import(pathToFileURL(path.join(CONTENT, slug, "primer.ts")).href);
  if (p.slug !== slug) throw new Error(`${slug}: primer.slug is ${p.slug}`);
  const content = {
    version: 1,
    summary: p.summary,
    prerequisites: p.prerequisites,
    walkthrough: p.walkthrough,
    template: { note: p.template.note, code: code(slug, p.template.code) },
    variants: p.variants.map((v) => ({ ...v, code: code(slug, v.code) })),
    complexity: p.complexity,
    notThis: p.notThis,
    ladder: p.ladder,
  };
  rows.push(`(${[
    lit(p.slug),
    lit(p.pattern),
    lit(p.title),
    arr(p.recognizeWhen),
    lit(p.coreIdea),
    lit(content.template.code.python),
    lit(`Time ${p.complexity.time} · Space ${p.complexity.space}`),
    arr(p.mistakes),
    arr(p.ladder.map((l) => l.slug).slice(0, 3)),
    String(p.order),
    json(content),
  ].join(",\n  ")})`);
}

const sql = `-- Generated by scripts/primers-to-sql.mjs from content/primers/. Do not edit;
-- change the content and generate a new migration instead.
--
-- Upserts the hand-written primers (${slugs.join(", ")}) on slug. Only
-- authorless rows are updated, so a member's own primer is never overwritten.
-- The legacy columns stay filled (template_md is the Python template) for
-- readers that don't know about \`content\` yet.

alter table public.primers add column if not exists roadmap_order int;
alter table public.primers add column if not exists content jsonb;
create index if not exists primers_roadmap_order_idx on public.primers (roadmap_order) where author_id is null;

insert into public.primers
  (slug, pattern, title, recognize_when, mental_model, template_md, complexity, mistakes, starter_slugs, roadmap_order, content)
values
${rows.join(",\n")}
on conflict (slug) do update set
  pattern = excluded.pattern,
  title = excluded.title,
  recognize_when = excluded.recognize_when,
  mental_model = excluded.mental_model,
  template_md = excluded.template_md,
  complexity = excluded.complexity,
  mistakes = excluded.mistakes,
  starter_slugs = excluded.starter_slugs,
  roadmap_order = excluded.roadmap_order,
  content = excluded.content
where public.primers.author_id is null;
`;

const out = path.join(ROOT, "supabase/migrations", `${version}_primers_content.sql`);
writeFileSync(out, sql);
console.log(`wrote ${path.relative(ROOT, out)} (${slugs.length} primer${slugs.length === 1 ? "" : "s"})`);
