"use client";

import React, { useState, useEffect, useCallback } from "react";
import Link from "next/link";
import { cn } from "@/lib/utils";
import { useAuth } from "@/components/providers/AuthProvider";
import { PageLoader } from "@/components/ui/PageLoader";
import { getSquadFeed, getGlobalFeed } from "@/lib/data/feed";
import { dataErrorMessage } from "@/lib/data/errors";
import { FeedEvent } from "@/types/database";

type Tab = "squad" | "global" | "platform";

const TYPE_LABEL: Record<string, string> = {
  solve: "solved",
  solved: "solved",
  challenge: "challenged",
  complete: "completed",
  completed: "completed",
  squad_milestone: "squad",
  stuck: "stuck",
  teach: "taught",
  resource: "shared",
  contest: "contest",
  improve: "improved",
  suggested: "suggested",
  streak: "streak",
};

function timeAgo(iso: string): string {
  const mins = Math.max(1, Math.round((Date.now() - new Date(iso).getTime()) / 60000));
  if (mins < 60) return `${mins}m ago`;
  const hrs = Math.round(mins / 60);
  if (hrs < 24) return `${hrs}h ago`;
  return `${Math.round(hrs / 24)}d ago`;
}

function describe(ev: FeedEvent): string {
  const who = ev.actor?.username ? `@${ev.actor.username}` : "Someone";
  switch (ev.event_type) {
    case "solve":
    case "solved":
      return `${who} solved ${ev.problem_title || "a problem"}`;
    case "challenge":
      return `${who} sent a challenge${ev.problem_title ? `: ${ev.problem_title}` : ""}`;
    case "complete":
    case "completed":
      return `${who} completed a challenge${ev.problem_title ? `: ${ev.problem_title}` : ""}`;
    case "squad_milestone": {
      const meta = ev.metadata as { kind?: string; title?: string };
      return meta.kind === "goal_set" ? `${who} set a squad goal: ${meta.title || "new goal"}` : `${who} hit a squad milestone`;
    }
    default:
      return `${who} · ${TYPE_LABEL[ev.event_type] || ev.event_type}`;
  }
}

export default function FeedPage() {
  const { profile } = useAuth();
  const [tab, setTab] = useState<Tab>("squad");
  const [events, setEvents] = useState<FeedEvent[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setLoadError(null);
    try {
      if (tab === "squad") {
        if (!profile?.active_squad_id) {
          setEvents([]);
          return;
        }
        setEvents(await getSquadFeed(profile.active_squad_id));
      } else if (tab === "global") {
        setEvents(await getGlobalFeed());
      } else {
        setEvents([]);
      }
    } catch (err) {
      setLoadError(dataErrorMessage(err, "Couldn't load feed. Retry."));
    } finally {
      setLoading(false);
    }
  }, [tab, profile?.active_squad_id]);

  useEffect(() => {
    load();
  }, [load]);

  return (
    <div className="space-y-6 select-none max-w-2xl">
      <div>
        <div className="text-[11px] font-semibold text-[#fa586a] tracking-[0.2em] uppercase mb-1">
          What are people learning?
        </div>
        <h1 className="text-3xl md:text-4xl font-extrabold text-white tracking-tight">Feed</h1>
        <p className="text-xs text-white/40 mt-1">Activity generated by learning — never posts for posting&apos;s sake.</p>
      </div>

      <div className="flex items-center gap-2 p-1 bg-white/[0.04] rounded-full border border-white/[0.06] w-fit">
        {(["squad", "global", "platform"] as Tab[]).map((t) => (
          <button
            key={t}
            onClick={() => setTab(t)}
            className={cn(
              "px-4 py-1.5 rounded-full text-xs font-semibold transition-all cursor-pointer capitalize",
              tab === t ? "bg-white/[0.12] text-white shadow-sm" : "text-white/40 hover:text-white/80"
            )}
          >
            {t}
          </button>
        ))}
        <span className="px-3 py-1.5 text-[11px] text-white/25 font-medium" title="Following arrives in Phase 4">
          Following · soon
        </span>
      </div>

      {/* Structured composer: actions, not a blank box (Bible §18). */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
        {[
          { label: "Share a solve", href: "/" },
          { label: "Challenge", href: "/suggestions" },
          { label: "Share resource", href: "/notebook" },
          { label: "Practice", href: "/practice" },
        ].map((a) => (
          <Link key={a.label} href={a.href}
            className="p-3 rounded-2xl bg-white/[0.03] hover:bg-white/[0.06] border border-white/[0.06] text-center text-[11px] font-bold text-white/70 hover:text-white transition-all">
            {a.label}
          </Link>
        ))}
      </div>

      {loadError && (
        <div role="alert" className="flex items-center justify-between gap-3 px-5 py-4 rounded-2xl bg-[#ff453a]/10 border border-[#ff453a]/30">
          <span className="text-xs text-[#ff453a] font-medium">{loadError}</span>
          <button onClick={load} className="px-4 py-1.5 rounded-full bg-[#ff453a]/15 text-[#ff453a] text-xs font-bold cursor-pointer shrink-0">Retry</button>
        </div>
      )}

      {loading ? (
        <PageLoader label="Loading feed..." className="h-40" />
      ) : tab === "platform" ? (
        <div className="space-y-2">
          <div className="p-4 rounded-2xl bg-white/[0.02] border border-white/[0.06] text-xs text-white/60">
            <span className="font-bold text-white">Phase 1 is live:</span> squads, Today&apos;s Battle, battle sessions with fail paths, problem timelines, approaches, beat-my-time challenges, and this feed.
          </div>
          <a href="https://leetcode.com/contest/" target="_blank" rel="noopener noreferrer"
            className="block p-4 rounded-2xl bg-white/[0.02] border border-white/[0.06] text-xs text-white/60 hover:border-white/[0.12] transition-all">
            <span className="font-bold text-white">Weekly Contest →</span> Squad ritual: compete, then compare approaches on Monday.
          </a>
        </div>
      ) : events.length === 0 ? (
        <div className="p-12 text-center space-y-3 bg-[#1c1c1e]/60 rounded-3xl border border-white/[0.06]">
          <p className="text-sm font-bold text-white">
            {tab === "squad" && !profile?.active_squad_id
              ? "No active squad."
              : "Quiet… for now."}
          </p>
          <p className="text-xs text-white/40 max-w-sm mx-auto">
            {tab === "squad" && !profile?.active_squad_id
              ? "Join or create a squad — solves and challenges will appear here automatically. No prose required."
              : "Solves, challenges, and completions land here on their own. Start today's battle."}
          </p>
          <Link href={tab === "squad" && !profile?.active_squad_id ? "/squad" : "/"}
            className="inline-block px-4 py-2 rounded-full bg-[#fa586a] text-white text-xs font-bold">
            {tab === "squad" && !profile?.active_squad_id ? "Find your squad" : "Start today's battle"}
          </Link>
        </div>
      ) : (
        <div className="space-y-2">
          {events.map((ev) => (
            <div key={ev.id} className="flex items-center gap-3 p-3.5 rounded-2xl bg-white/[0.02] border border-white/[0.06] text-xs">
              <div className="w-7 h-7 rounded-full bg-white/[0.06] border border-white/[0.08] flex items-center justify-center font-bold text-[10px] text-white shrink-0 overflow-hidden">
                {ev.actor?.avatar_url ? (
                  // eslint-disable-next-line @next/next/no-img-element
                  <img src={ev.actor.avatar_url} alt={ev.actor.username} className="w-full h-full object-cover" />
                ) : (
                  (ev.actor?.username || "?").charAt(0).toUpperCase()
                )}
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-white/80 truncate">{describe(ev)}</p>
                <p className="text-[10px] text-white/30 font-mono">{timeAgo(ev.created_at)}</p>
              </div>
              {ev.problem_slug && (
                <Link href={`/practice/${ev.problem_slug}`} className="px-3 py-1 rounded-full bg-white/[0.04] hover:bg-white/[0.08] border border-white/[0.06] text-white/60 text-[11px] font-semibold shrink-0 transition-all">
                  Open
                </Link>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
